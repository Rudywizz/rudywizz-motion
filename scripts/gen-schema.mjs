#!/usr/bin/env node
// Generates skills/rudywizz-motion/schema/composition.schema.json from the live engine
// (styles + their options, cameras, transitions, looks, grades) so editors can
// autocomplete and validate composition files. Run via `npm run skills`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENGINE = path.join(ROOT, 'skills/rudywizz-motion/engine');
const STYLES = path.join(ROOT, 'skills/rudywizz-motion/styles');
const OUT = path.join(ROOT, 'skills/rudywizz-motion/schema/composition.schema.json');

const { TRANSITIONS, LOOKS, GRADES } = await import(pathToFileURL(path.join(ENGINE, 'timeline.js')).href);
const { CAMERA_PRESETS } = await import(pathToFileURL(path.join(ENGINE, 'camera.js')).href);

const styles = {};
for (const id of fs.readdirSync(STYLES).filter((d) => fs.existsSync(path.join(STYLES, d, 'style.js'))).sort()) {
  styles[id] = (await import(pathToFileURL(path.join(STYLES, id, 'style.js')).href)).default;
}

const typeOf = (v) => (Array.isArray(v) ? 'array' : v === null ? 'null' : typeof v === 'number' ? 'number' : typeof v);
const styleProps = (s) => {
  const props = {};
  for (const [k, v] of Object.entries(s.defaults || {})) {
    if (k === 'duration') continue;
    props[k] = { description: s.options?.[k] || (k === 'text' ? 'Text (" / " or \\n for line breaks)' : undefined), default: v, type: typeOf(v) };
    if (props[k].type === 'array' || props[k].type === 'object') delete props[k].type; // keep permissive
  }
  for (const [k, d] of Object.entries(s.options || {})) if (!props[k]) props[k] = { description: d };
  return props;
};

const camera = {
  description: 'Camera move: a preset name or { preset, amount, shake, keys }',
  anyOf: [
    { type: 'string', enum: Object.keys(CAMERA_PRESETS) },
    {
      type: 'object',
      properties: {
        preset: { type: 'string', enum: Object.keys(CAMERA_PRESETS) },
        amount: { type: 'number', description: 'Strength multiplier (1 = preset)' },
        shake: { type: 'number', description: 'Handheld shake amount' },
        keys: {
          type: 'array',
          items: {
            type: 'object',
            properties: {
              at: { type: 'number', minimum: 0, maximum: 1, description: 'Fraction of the scene' },
              t: { type: 'number', description: 'Seconds into the scene' },
              x: { type: 'number' }, y: { type: 'number' }, zoom: { type: 'number' }, rot: { type: 'number' },
              tx: { type: 'number' }, ty: { type: 'number' }, lens: { type: 'number' },
              ease: { type: 'string', enum: ['linear', 'outExpo', 'inOutCubic', 'inOutSine', 'outCubic', 'inCubic'] },
            },
          },
        },
      },
    },
  ],
};
const transition = {
  description: 'Transition into the next scene (sits on the scene it leaves)',
  anyOf: [
    { type: 'string', enum: TRANSITIONS },
    {
      type: 'object',
      required: ['type'],
      properties: {
        type: { type: 'string', enum: TRANSITIONS },
        duration: { type: 'number', minimum: 0, description: 'Seconds the two scenes overlap' },
        dir: { anyOf: [{ type: 'string', enum: ['left', 'right', 'up', 'down'] }, { type: 'array', items: { type: 'number' } }] },
      },
    },
  ],
};
const look = {
  description: 'Image/clip filter',
  anyOf: [
    { type: 'string', enum: LOOKS },
    {
      type: 'object',
      required: ['type'],
      properties: {
        type: { type: 'string', enum: LOOKS },
        reveal: { type: 'number', description: 'Seconds for the engrave/sketch draw-on' },
        delay: { type: 'number' },
        paper: { type: 'string' },
        ink: { type: 'string' },
      },
    },
  ],
};
const styleRef = (extra = {}) => ({
  type: 'object',
  required: ['style'],
  properties: { style: { type: 'string', enum: Object.keys(styles) }, ...extra },
  allOf: Object.entries(styles).map(([id, s]) => ({ if: { properties: { style: { const: id } } }, then: { properties: styleProps(s) } })),
});

const schema = {
  $schema: 'http://json-schema.org/draft-07/schema#',
  $id: 'https://raw.githubusercontent.com/Rudywizz/rudywizz-motion/main/skills/rudywizz-motion/schema/composition.schema.json',
  title: 'rudywizz-motion composition',
  description: 'A video made of scenes played back to back. Generated by scripts/gen-schema.mjs — do not edit by hand.',
  type: 'object',
  required: ['scenes'],
  properties: {
    $schema: { type: 'string' },
    name: { type: 'string' },
    description: { type: 'string' },
    format: { type: 'string', enum: ['9:16', '1:1', '4:5', '16:9'], default: '9:16' },
    width: { type: 'integer', minimum: 16 },
    height: { type: 'integer', minimum: 16 },
    fps: { type: 'number', minimum: 1, maximum: 120, default: 30 },
    seed: { type: 'number', description: 'Same seed → same video' },
    lang: { type: 'string', description: 'Language for casing rules, e.g. "tr" (i → İ)' },
    bpm: { type: 'number', description: 'Tempo for beat-synced styles and the beat-punch camera' },
    audio: { type: 'string', description: 'Audio file path (relative to this JSON)' },
    music: {
      description: 'Code-made, royalty-free music as long as the video; ducks under voice lines. Ignored when "audio" is set.',
      oneOf: [
        { enum: ['upbeat', 'chill', 'retro', 'cinematic'] },
        {
          type: 'object',
          additionalProperties: false,
          required: ['mood'],
          properties: {
            mood: { enum: ['upbeat', 'chill', 'retro', 'cinematic'] },
            bpm: { type: 'number', minimum: 50, maximum: 200, description: 'Tempo (defaults to the mood, or the composition bpm)' },
            key: { type: 'string', description: 'Key, e.g. "F", "C#", "Bb"' },
            seed: { type: 'number', description: 'Another seed = another melody' },
            volume: { type: 'number', minimum: 0, maximum: 2, description: 'Music level under voices (default 0.5)' },
          },
        },
      ],
    },
    alpha: { type: 'boolean', description: 'Transparent background (.mov / .webm output)' },
    motionBlur: { type: 'integer', minimum: 1, maximum: 16, description: 'Sub-frames per frame (4–8 = filmic)' },
    cameraBlur: { type: 'boolean', default: true },
    look: {
      type: 'object',
      description: 'Global post chain',
      properties: {
        grade: { type: 'string', enum: GRADES },
        gradeAmount: { type: 'number', minimum: 0, maximum: 1 },
        bloom: { type: 'number', minimum: 0 }, grain: { type: 'number', minimum: 0 }, leak: { type: 'number', minimum: 0 },
        film: { type: 'number', minimum: 0 }, aberration: { type: 'number', minimum: 0 }, vignette: { type: 'number', minimum: 0 },
        distortion: { type: 'number' }, weave: { type: 'number', minimum: 0 },
      },
      additionalProperties: false,
    },
    scenes: {
      type: 'array',
      minItems: 1,
      items: {
        type: 'object',
        properties: {
          style: { type: 'string', enum: Object.keys(styles), description: 'A style id (run `rudywizz-motion list`)' },
          image: { type: 'string', description: 'Image path (jpg/png/svg/webp)' },
          layers: { type: 'array', items: { type: 'object', properties: { src: { type: 'string' }, depth: { type: 'number' }, x: { type: 'number' }, y: { type: 'number' }, scale: { type: 'number' }, fit: { enum: ['cover', 'contain'] } } } },
          clip: { type: 'string', description: 'Video clip path' },
          in: { type: 'number', description: 'Clip start in seconds' },
          speed: { anyOf: [{ type: 'number', exclusiveMinimum: 0 }, { type: 'string', enum: ['ramp-in', 'ramp-out', 'ramp-mid'] }] },
          color: { type: 'string' },
          fit: { type: 'string', enum: ['cover', 'contain'] },
          duration: { type: 'number', exclusiveMinimum: 0 },
          camera,
          look,
          transition,
          overlay: styleRef({ at: { type: 'number', description: 'Start offset in seconds' } }),
          params: { type: 'object' },
        },
        anyOf: [{ required: ['style'] }, { required: ['image'] }, { required: ['layers'] }, { required: ['clip'] }, { required: ['color'] }],
        allOf: Object.entries(styles).map(([id, s]) => ({ if: { properties: { style: { const: id } }, required: ['style'] }, then: { properties: styleProps(s) } })),
      },
    },
    overlays: {
      type: 'array',
      description: 'Styles drawn on top of everything, ungraded',
      items: styleRef({ from: { type: 'number' }, to: { type: 'number' } }),
    },
  },
};

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(schema, null, 2) + '\n');
console.log(`schema: ${Object.keys(styles).length} styles → ${path.relative(ROOT, OUT)}`);
